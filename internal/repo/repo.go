// Package repo manages the apps git repo: the source of truth for what coolix
// deploys. Its flake.nix is generated from the app list; app.toml files are
// the real data.
package repo

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"coolix/internal/appdef"
	"coolix/internal/gitpush"
)

type Repo struct {
	Dir string
	// Nixpkgs and Lib are store paths pinned as the repo's nixpkgs and coolix inputs.
	Nixpkgs string
	Lib     string
	System  string
	// GitDir holds the bare repos of push apps (<name>.git).
	GitDir string
}

// GenerateFlake renders flake.nix for the given apps. Apps in skip (push
// apps with nothing pushed yet) get no input and aren't built.
func (r *Repo) GenerateFlake(apps []*appdef.App, skip []string) string {
	var b strings.Builder
	b.WriteString("# Generated by coolix; do not edit. Rewritten whenever apps are added or removed.\n")
	b.WriteString("{\n  inputs = {\n")
	fmt.Fprintf(&b, "    nixpkgs.url = \"path:%s\";\n", r.Nixpkgs)
	fmt.Fprintf(&b, "    coolix.url = \"path:%s\";\n", r.Lib)
	b.WriteString("    coolix.inputs.nixpkgs.follows = \"nixpkgs\";\n")
	for _, a := range apps {
		if slices.Contains(skip, a.Name) {
			continue
		}
		src := a.Source
		if a.Pushed() {
			src = gitpush.FlakeURL(gitpush.Dir(r.GitDir, a.Name), a.DeployBranch())
		}
		fmt.Fprintf(&b, "    app-%s.url = \"%s\";\n", a.Name, src)
		if a.FollowsNixpkgs() {
			fmt.Fprintf(&b, "    app-%s.inputs.nixpkgs.follows = \"nixpkgs\";\n", a.Name)
		}
	}
	b.WriteString("  };\n\n")
	fmt.Fprintf(&b, "  outputs = inputs: inputs.coolix.lib.mkAppProfile {\n    inherit inputs;\n    root = ./.;\n    system = \"%s\";\n", r.System)
	if len(skip) > 0 {
		fmt.Fprintf(&b, "    skip = [ \"%s\" ];\n", strings.Join(skip, "\" \""))
	}
	b.WriteString("  };\n}\n")
	return b.String()
}

func (r *Repo) git(args ...string) error {
	cmd := exec.Command("git", append([]string{
		"-c", "user.name=coolix", "-c", "user.email=coolix@localhost", "-c", "commit.gpgsign=false",
	}, args...)...)
	cmd.Dir = r.Dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("git %s: %w\n%s", strings.Join(args, " "), err, out)
	}
	return nil
}

// Init creates the repo if it doesn't exist yet.
func (r *Repo) Init() error {
	if _, err := os.Stat(filepath.Join(r.Dir, ".git")); err == nil {
		return nil
	}
	if err := os.MkdirAll(filepath.Join(r.Dir, "apps"), 0o755); err != nil {
		return err
	}
	if err := r.git("init", "-q", "-b", "main"); err != nil {
		return err
	}
	if err := r.WriteFlake(nil, nil); err != nil {
		return err
	}
	return r.Commit("Initialize coolix apps repo")
}

func (r *Repo) WriteFlake(apps []*appdef.App, skip []string) error {
	return os.WriteFile(filepath.Join(r.Dir, "flake.nix"), []byte(r.GenerateFlake(apps, skip)), 0o644)
}

// Sync regenerates flake.nix from the current app.toml files.
func (r *Repo) Sync() ([]*appdef.App, error) {
	apps, err := appdef.LoadAll(r.Dir)
	if err != nil {
		return nil, err
	}
	return apps, r.WriteFlake(apps, r.Unpushed(apps))
}

// Unpushed returns the push apps whose deploy branch hasn't been pushed yet.
func (r *Repo) Unpushed(apps []*appdef.App) []string {
	var out []string
	for _, a := range apps {
		if a.Pushed() && !gitpush.HasBranch(gitpush.Dir(r.GitDir, a.Name), a.DeployBranch()) {
			out = append(out, a.Name)
		}
	}
	return out
}

// Commit stages everything and commits; a no-op if nothing changed.
func (r *Repo) Commit(msg string) error {
	if err := r.git("add", "-A"); err != nil {
		return err
	}
	cmd := exec.Command("git", "diff", "--cached", "--quiet")
	cmd.Dir = r.Dir
	if cmd.Run() == nil {
		return nil
	}
	return r.git("commit", "-q", "-m", msg)
}

// RestoreTree makes the working tree and index match rev (deleting files
// added since), ready to be committed as a rollback.
func (r *Repo) RestoreTree(rev string) error {
	if err := r.git("rev-parse", "--verify", "--quiet", rev+"^{commit}"); err != nil {
		return fmt.Errorf("revision %s not found in apps repo", rev)
	}
	return r.git("read-tree", "-u", "--reset", rev)
}

func (r *Repo) RemoveApp(name string) error {
	dir := filepath.Join(r.Dir, "apps", name)
	if _, err := os.Stat(dir); err != nil {
		return fmt.Errorf("app %q does not exist", name)
	}
	return os.RemoveAll(dir)
}

// Head returns the current commit of the apps repo.
func (r *Repo) Head() (string, error) {
	cmd := exec.Command("git", "rev-parse", "HEAD")
	cmd.Dir = r.Dir
	out, err := cmd.Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

// SameTree reports whether rev has the same content as HEAD (a rollback
// commit restores an old tree under a new commit).
func (r *Repo) SameTree(rev string) bool {
	tree := func(ref string) string {
		cmd := exec.Command("git", "rev-parse", "--verify", "--quiet", ref+"^{tree}")
		cmd.Dir = r.Dir
		out, err := cmd.Output()
		if err != nil {
			return ""
		}
		return strings.TrimSpace(string(out))
	}
	a := tree(rev)
	return a != "" && a == tree("HEAD")
}

// Clone makes a private working copy of rev at dst on branch "deploy", so
// slow work (locking inputs fetches from the network) can happen without
// holding up edits to the main repo.
func (r *Repo) Clone(dst, rev string) (*Repo, error) {
	if err := os.RemoveAll(dst); err != nil {
		return nil, err
	}
	if err := r.git("clone", "-q", "--shared", "--no-checkout", r.Dir, dst); err != nil {
		return nil, err
	}
	c := &Repo{Dir: dst, Nixpkgs: r.Nixpkgs, Lib: r.Lib, System: r.System, GitDir: r.GitDir}
	return c, c.git("checkout", "-q", "-B", "deploy", rev)
}

// Adopt brings the "deploy" branch of clone back into r. If r is still at
// base it fast-forwards; otherwise (edits happened meanwhile) only
// flake.lock is taken over and committed with msg. It returns the commit of
// the clone, which is what gets built.
func (r *Repo) Adopt(clone *Repo, base, msg string) (string, error) {
	if err := r.git("fetch", "-q", clone.Dir, "+refs/heads/deploy:refs/coolix/deploy"); err != nil {
		return "", err
	}
	built, err := r.revParse("refs/coolix/deploy")
	if err != nil {
		return "", err
	}
	// Keep every built commit reachable: generations refer to it, and a
	// rollback restores the repo to it (git gc would prune it otherwise).
	if err := r.git("update-ref", "refs/coolix/built/"+built, built); err != nil {
		return "", err
	}
	head, err := r.Head()
	if err != nil {
		return "", err
	}
	if head == base {
		return built, r.git("merge", "-q", "--ff-only", "refs/coolix/deploy")
	}
	if err := r.git("checkout", "refs/coolix/deploy", "--", "flake.lock"); err != nil {
		return "", err
	}
	return built, r.Commit(msg)
}

func (r *Repo) revParse(ref string) (string, error) {
	cmd := exec.Command("git", "rev-parse", "--verify", "--quiet", ref+"^{commit}")
	cmd.Dir = r.Dir
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("git rev-parse %s: %w", ref, err)
	}
	return strings.TrimSpace(string(out)), nil
}
